CREATE TABLE volunteer_applications (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  reference_code VARCHAR(32) NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL,
  phone VARCHAR(80) NOT NULL DEFAULT '',
  country VARCHAR(120) NOT NULL,
  preferred_language VARCHAR(40) NOT NULL,
  program VARCHAR(60) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  dates_flexible TINYINT(1) NOT NULL DEFAULT 0,
  interests_json JSON NOT NULL,
  tropical_experience VARCHAR(120) NOT NULL,
  background TEXT NOT NULL,
  motivation TEXT NOT NULL,
  contribution TEXT NOT NULL,
  practical_needs TEXT NOT NULL,
  updates_opt_in TINYINT(1) NOT NULL DEFAULT 0,
  form_language VARCHAR(5) NOT NULL DEFAULT 'en',
  status ENUM('new','reviewing','contacted','accepted','declined','withdrawn') NOT NULL DEFAULT 'new',
  reviewer_notes TEXT NULL,
  ip_hash CHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_volunteer_reference (reference_code),
  KEY idx_volunteer_status_created (status, created_at),
  KEY idx_volunteer_email (email),
  KEY idx_volunteer_ip_created (ip_hash, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
